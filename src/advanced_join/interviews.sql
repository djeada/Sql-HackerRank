WITH submissions AS (
    SELECT CHALLENGE_ID,
           SUM(TOTAL_SUBMISSIONS) AS TOTAL_SUBMISSIONS,
           SUM(TOTAL_ACCEPTED_SUBMISSIONS) AS TOTAL_ACCEPTED_SUBMISSIONS
    FROM SUBMISSION_STATS
    GROUP BY CHALLENGE_ID
), views AS (
    SELECT CHALLENGE_ID,
           SUM(TOTAL_VIEWS) AS TOTAL_VIEWS,
           SUM(TOTAL_UNIQUE_VIEWS) AS TOTAL_UNIQUE_VIEWS
    FROM VIEW_STATS
    GROUP BY CHALLENGE_ID
)
SELECT C.CONTEST_ID, C.HACKER_ID, C.NAME,
       COALESCE(SUM(S.TOTAL_SUBMISSIONS), 0) AS TOTAL_SUBMISSIONS,
       COALESCE(SUM(S.TOTAL_ACCEPTED_SUBMISSIONS), 0) AS TOTAL_ACCEPTED_SUBMISSIONS,
       COALESCE(SUM(V.TOTAL_VIEWS), 0) AS TOTAL_VIEWS,
       COALESCE(SUM(V.TOTAL_UNIQUE_VIEWS), 0) AS TOTAL_UNIQUE_VIEWS
FROM CONTESTS AS C
JOIN COLLEGES AS CO ON CO.CONTEST_ID = C.CONTEST_ID
JOIN CHALLENGES AS CH ON CH.COLLEGE_ID = CO.COLLEGE_ID
LEFT JOIN submissions AS S ON S.CHALLENGE_ID = CH.CHALLENGE_ID
LEFT JOIN views AS V ON V.CHALLENGE_ID = CH.CHALLENGE_ID
GROUP BY C.CONTEST_ID, C.HACKER_ID, C.NAME
HAVING COALESCE(SUM(S.TOTAL_SUBMISSIONS), 0)
     + COALESCE(SUM(S.TOTAL_ACCEPTED_SUBMISSIONS), 0)
     + COALESCE(SUM(V.TOTAL_VIEWS), 0)
     + COALESCE(SUM(V.TOTAL_UNIQUE_VIEWS), 0) > 0
ORDER BY C.CONTEST_ID;
