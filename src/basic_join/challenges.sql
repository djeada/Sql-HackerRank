WITH counts AS (
    SELECT H.HACKER_ID, H.NAME, COUNT(*) AS CHALLENGE_COUNT
    FROM HACKERS AS H
    JOIN CHALLENGES AS C ON C.HACKER_ID = H.HACKER_ID
    GROUP BY H.HACKER_ID, H.NAME
)
SELECT HACKER_ID, NAME, CHALLENGE_COUNT
FROM counts
WHERE CHALLENGE_COUNT = (SELECT MAX(CHALLENGE_COUNT) FROM counts)
   OR CHALLENGE_COUNT IN (
       SELECT CHALLENGE_COUNT
       FROM counts
       GROUP BY CHALLENGE_COUNT
       HAVING COUNT(*) = 1
   )
ORDER BY CHALLENGE_COUNT DESC, HACKER_ID;
