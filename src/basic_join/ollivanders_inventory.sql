SELECT W.ID, P.AGE, W.COINS_NEEDED, W.POWER
FROM WANDS AS W
JOIN WANDS_PROPERTY AS P ON P.CODE = W.CODE
WHERE P.IS_EVIL = 0
  AND W.COINS_NEEDED = (
      SELECT MIN(W2.COINS_NEEDED)
      FROM WANDS AS W2
      JOIN WANDS_PROPERTY AS P2 ON P2.CODE = W2.CODE
      WHERE P2.IS_EVIL = 0 AND P2.AGE = P.AGE AND W2.POWER = W.POWER
  )
ORDER BY W.POWER DESC, P.AGE DESC, W.ID;
