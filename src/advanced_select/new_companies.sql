SELECT C.COMPANY_CODE, C.FOUNDER,
       (SELECT COUNT(DISTINCT L.LEAD_MANAGER_CODE)
        FROM LEAD_MANAGER AS L WHERE L.COMPANY_CODE = C.COMPANY_CODE),
       (SELECT COUNT(DISTINCT S.SENIOR_MANAGER_CODE)
        FROM SENIOR_MANAGER AS S WHERE S.COMPANY_CODE = C.COMPANY_CODE),
       (SELECT COUNT(DISTINCT M.MANAGER_CODE)
        FROM MANAGER AS M WHERE M.COMPANY_CODE = C.COMPANY_CODE),
       (SELECT COUNT(DISTINCT E.EMPLOYEE_CODE)
        FROM EMPLOYEE AS E WHERE E.COMPANY_CODE = C.COMPANY_CODE)
FROM COMPANY AS C
ORDER BY C.COMPANY_CODE;
